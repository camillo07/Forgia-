import asyncio
from playwright.async_api import async_playwright
from testlib import setup_fake
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        await setup_fake(ctx)
        pg = await ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/index.html'); await pg.wait_for_timeout(700)
        await pg.fill('#ob-name', 'Mattia'); await pg.click('input[value="ppl"]'); await pg.check('#ob-demo')
        await pg.click('[data-a="finishOnboard"]'); await pg.wait_for_timeout(800)
        await pg.evaluate("() => { S.nutri = defaultNutri(); save(); }")
        print('weights', await pg.evaluate("() => [bodyWeight(), lastWeight(), dietWeight(), liveNutri(S.nutri).weight, baseTargets().p]"))
        await pg.click('[data-a="tab"][data-k="progress"]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path='shots/a1-progress.png', full_page=True)
        print('corr', (await pg.inner_text('.corr')).replace('\n', ' | ')[:400])
        print('map groups', await pg.evaluate("() => [...document.querySelectorAll('.bodymap .mm title')].map(t => t.textContent).join('; ')"))
        await pg.click('[data-a="progSeg"][data-v="body"]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path='shots/a2-body.png', full_page=True)
        print('w7', (await pg.inner_text('.w7s')).replace('\n', ' '))
        k = await pg.evaluate("() => document.querySelectorAll('.w7')[3].dataset.k")
        await pg.click('.w7 >> nth=3'); await pg.wait_for_timeout(300)
        print('bodyLog for', k, await pg.evaluate("() => [topLayer().type, topLayer().k]"))
        await pg.evaluate("() => { UI.layers = []; render(); }")
        await pg.click('[data-a="tab"][data-k="diet"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-a="nutriSetup"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/a3-nutri.png', full_page=True)
        print('nutri draft w', await pg.evaluate("() => topLayer().draft.weight"))
        await pg.click('[data-a="ntWMode"][data-v="last"]'); await pg.wait_for_timeout(200)
        print('after last', await pg.evaluate("() => topLayer().draft.weight"))
        await pg.click('[data-a="nutriSave"]'); await pg.wait_for_timeout(300)
        print('saved', await pg.evaluate("() => [S.nutri.wMode, liveNutri(S.nutri).weight, baseTargets().p]"))
        print('hoverflow', await pg.evaluate("() => document.documentElement.scrollWidth > innerWidth"), 'ERR', errs)
        await b.close()
asyncio.run(main())
